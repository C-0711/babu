    (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     mandant_id INTEGER NOT NULL,
     quelle TEXT NOT NULL,
     aktion TEXT NOT NULL,
     stufe TEXT,
     zeit TEXT NOT NULL);
